grant select, insert, update, delete on table public.ai_faculty_data to anon, authenticated;
grant usage, select on sequence public.admin_activity_log_simple_id_seq to anon, authenticated;

-- 5) Verify login. Returns admin details only when username/password match.
create or replace function public.verify_admin_login(
  p_username text,
  p_password text
)
returns table (
  id bigint,
  username text,
  role text,
  is_active boolean,
  created_at timestamptz
)
language sql
security definer
set search_path = public, extensions
as $$
  select a.id, a.username, a.role, a.is_active, a.created_at
  from public.admin_login_users a
  where lower(a.username) = lower(trim(p_username))
    and a.is_active = true
    and a.password_hash = extensions.crypt(p_password, a.password_hash)
  limit 1;
$$;

-- 6) List admin users after re-checking the current admin password.
create or replace function public.list_admin_login_users(
  p_admin_username text,
  p_admin_password text
)
returns table (
  id bigint,
  username text,
  role text,
  is_active boolean,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if not exists (
    select 1 from public.admin_login_users a
    where lower(a.username)=lower(trim(p_admin_username))
      and a.is_active=true
      and a.password_hash=extensions.crypt(p_admin_password,a.password_hash)
  ) then
    raise exception 'Invalid administrator credentials';
  end if;

  return query
  select a.id,a.username,a.role,a.is_active,a.created_at
  from public.admin_login_users a
  order by a.created_at desc;
end;
$$;

-- 7) Add an admin. Current admin credentials are verified first.
create or replace function public.add_admin_login_user(
  p_admin_username text,
  p_admin_password text,
  p_username text,
  p_password text,
  p_role text default 'admin'
)
returns table (id bigint, username text)
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_id bigint;
  v_username text;
begin
  if not exists (
    select 1 from public.admin_login_users a
    where lower(a.username)=lower(trim(p_admin_username))
      and a.is_active=true
      and a.role='super_admin'
      and a.password_hash=extensions.crypt(p_admin_password,a.password_hash)
  ) then
    raise exception 'Super Admin credentials required';
  end if;

  if length(trim(p_username)) < 3 then
    raise exception 'User ID must be at least 3 characters';
  end if;

  if length(p_password) < 8 then
    raise exception 'Password must be at least 8 characters';
  end if;

  if p_role not in ('admin','super_admin') then
    raise exception 'Invalid role';
  end if;

  insert into public.admin_login_users(username,password_hash,role,is_active)
  values (trim(p_username), extensions.crypt(p_password, extensions.gen_salt('bf', 10)), p_role, true)
  returning admin_login_users.id, admin_login_users.username into v_id, v_username;

  return query select v_id, v_username;
end;
$$;

-- 8) Disable/reactivate an admin. Current super-admin credentials are verified.
create or replace function public.set_admin_login_user_active(
  p_admin_username text,
  p_admin_password text,
  p_user_id bigint,
  p_active boolean
)
returns table (username text)
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_current_id bigint;
  v_username text;
begin
  select a.id into v_current_id
  from public.admin_login_users a
  where lower(a.username)=lower(trim(p_admin_username))
    and a.is_active=true
    and a.role='super_admin'
    and a.password_hash=extensions.crypt(p_admin_password,a.password_hash)
  limit 1;

  if v_current_id is null then
    raise exception 'Super Admin credentials required';
  end if;

  if v_current_id = p_user_id and p_active = false then
    raise exception 'You cannot disable your own account';
  end if;

  update public.admin_login_users
  set is_active=p_active
  where id=p_user_id
  returning admin_login_users.username into v_username;

  if v_username is null then
    raise exception 'Admin user not found';
  end if;

  return query select v_username;
end;
$$;

grant execute on function public.verify_admin_login(text,text) to anon, authenticated;
