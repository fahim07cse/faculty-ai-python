-- ============================================================
-- ADMIN DATABASE LOGIN WITH HASHED PASSWORDS
-- Supabase PostgreSQL + pgcrypto
-- Passwords are NOT stored as plain text.
-- ============================================================

create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

-- 1) Faculty soft-delete columns.
alter table public.ai_faculty_data
  add column if not exists is_deleted boolean not null default false;

alter table public.ai_faculty_data
  add column if not exists deleted_at timestamptz;

-- 2) Admin login table. Store only password_hash.
create table if not exists public.admin_login_users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,
  role text not null default 'admin'
    check (role in ('admin', 'super_admin')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- If an older plain-text password column exists, migrate it to password_hash.
do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema='public'
      and table_name='admin_login_users'
      and column_name='password'
  ) then
    execute $migrate$
      update public.admin_login_users
      set password_hash = extensions.crypt(password, extensions.gen_salt('bf', 10))
      where (password_hash is null or password_hash = '')
        and password is not null
    $migrate$;
  end if;
end $$;

-- 3) Activity log.
create table if not exists public.admin_activity_log_simple (
