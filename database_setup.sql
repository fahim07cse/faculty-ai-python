alter table public.admin_login_users enable row level security;
revoke all on table public.admin_login_users from anon, authenticated;

-- Demo project: faculty data and activity log remain directly accessible.
alter table public.admin_activity_log_simple disable row level security;
alter table public.ai_faculty_data disable row level security;
